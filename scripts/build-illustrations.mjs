// Builds the brand illustration sprite from the drawn set.
//
//   node scripts/build-illustrations.mjs        (npm run art:illustrations)
//
// Source: ekhizmat-app-illustrations/*.svg — 100×100 line drawings in one
// navy outline, white paper, a six-step blue ramp, gold and sand. Output:
// design-system/assets/illustrations.svg, one <symbol id="ill-<file name>">
// per drawing, used like the icon sprite:
//
//   <svg class="ekh-ill" aria-hidden="true"><use href="/design-system/assets/illustrations.svg#ill-service-marriage"/></svg>
//
// Every colour becomes a role token (--ill-*, design-system/tokens/color.css)
// written as an inline style — the only styling a <use> clone of an external
// sprite keeps — with the drawn value as its fallback, so light mode renders
// exactly as drawn and dark mode re-colours the same drawing instead of
// shipping a second set. Illustrations are scenes for life situations, empty
// and success states; service icons stay in icons.svg (design-guide §3).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'ekhizmat-app-illustrations');
const out = join(root, 'design-system/assets/illustrations.svg');

/* drawn value → role token; the ramp runs from the palest tint to the deepest */
const ROLES = {
  '#1B3B6F': 'ill-line',
  '#FFFFFF': 'ill-paper',
  '#E3EEFD': 'ill-tint-1',
  '#D9E9FD': 'ill-tint-2',
  '#C9E0FB': 'ill-tint-3',
  '#BBD9FB': 'ill-tint-4',
  '#AACFFA': 'ill-tint-5',
  '#9CC6F9': 'ill-tint-6',
  '#F8CD7E': 'ill-gold',
  '#F3D9B8': 'ill-sand',
};

const symbols = [];
for (const file of readdirSync(src).filter(f => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(src, file), 'utf8');
  const label = (svg.match(/aria-label="([^"]*)"/) || [])[1] || '';
  /* the drawings wrap their paths in an identity transform; keep only the paths */
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/<g transform="translate\(50 50\) scale\(1\) translate\(-50 -50\)">([\s\S]*)<\/g>/, '$1');
  const themed = body.replace(/<(path|circle|rect|ellipse|line|polyline|polygon)\b([^>]*?)(\/?)>/g, (tag, name, attrs, close) => {
    const style = [];
    attrs = attrs.replace(/\s(fill|stroke)="(#[0-9A-Fa-f]{6})"/g, (m, prop, hex) => {
      const role = ROLES[hex.toUpperCase()];
      if (!role) throw new Error(`${file}: ${hex} has no role — add it to ROLES and color.css`);
      style.push(`${prop}:var(--${role},${hex.toUpperCase()})`);
      return '';
    });
    return `<${name}${attrs}${style.length ? ` style="${style.join(';')}"` : ''}${close}>`;
  });
  symbols.push(`  <!-- ${label} -->\n  <symbol id="ill-${file.replace(/\.svg$/, '')}" viewBox="0 0 100 100">${themed}</symbol>`);
}

writeFileSync(out, `<?xml version="1.0" encoding="UTF-8"?>
<!-- eKhizmat — brand illustrations. GENERATED by scripts/build-illustrations.mjs
     from ekhizmat-app-illustrations/ — edit the drawings, then rebuild; never edit by hand.
     Colours are the ill-* role tokens of design-system/tokens/color.css, the drawn value as fallback.
     (No double hyphen may appear inside an XML comment: the whole sprite would fail to parse.) -->
<svg xmlns="http://www.w3.org/2000/svg" style="display:none">
${symbols.join('\n')}
</svg>
`);
console.log(`${symbols.length} illustrations → ${out.replace(root + '/', '')}`);
