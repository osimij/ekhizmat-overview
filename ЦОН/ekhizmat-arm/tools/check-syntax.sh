#!/bin/bash
# Проверка синтаксиса всех ES-модулей проекта.
#
# Осторожно: `node --check file.js` для них БЕСПОЛЕЗЕН — он разбирает файл как
# скрипт и молча выходит с нулём, пропуская даже пропущенную скобку. Ошибку
# потом ловит только браузер, и выглядит она как пустая белая страница: модуль
# не распарсился, `boot().catch(fatal)` не выполнился, показать ошибку некому.
# Расширение .mjs заставляет node разбирать файл как модуль — это и есть
# настоящая проверка.
set -u
cd "$(dirname "$0")/.."
fail=0
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

for f in $(find js -name '*.js' | sort); do
  cp "$f" "$tmp/m.mjs"
  if ! out=$(node --check "$tmp/m.mjs" 2>&1); then
    echo "❌ $f"
    echo "$out" | sed -n '2,4p'
    fail=1
  fi
done

[ "$fail" = 0 ] && echo "✓ синтаксис: все модули разбираются"
exit $fail
